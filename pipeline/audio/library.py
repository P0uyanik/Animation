"""The vocal sound library (T-195): content/sounds/SOURCES.json and the files it lists.

    content/sounds/library/<cue>/<file>.wav    48 kHz mono 16-bit PCM (any integer PCM WAV is read)
    content/sounds/SOURCES.json                 one entry per file: sha256, cue, licence, source, evidence, placeholder

Rules (checked by `check()` and the tests):
  - every WAV under library/ has exactly one entry and its sha256 matches;
  - licence is one of ALLOWED_LICENCES (CC0-1.0 or project-own); anything else (BY, SA, NC, "royalty free"...) fails;
  - a non-procedural entry needs `evidence` (licence URL or the owner's statement) and `source.url` or `source.by`.
Choice: for a cue, files with placeholder false win over placeholders when any exist (so a recorded / approved CC0
file replaces the procedural stand-ins with no code change); among the candidates the variant is picked by hash.
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

if __package__:
    from . import synth, wavio
else:
    import synth
    import wavio

ROOT = Path(__file__).resolve().parents[2]
SOUNDS = ROOT / "content" / "sounds"
SOURCES = "SOURCES.json"
ALLOWED_LICENCES = ("CC0-1.0", "project-own")
# Procedural placeholder set: cue -> number of variants.
PLACEHOLDERS = {"gasp_oh": 3, "wow": 3, "giggle": 3, "laugh": 2, "hm": 2, "sigh": 2}


def load_sources(sounds: Path = SOUNDS) -> dict:
    p = sounds / SOURCES
    if not p.exists():
        return {"format": "plush.soundsources", "version": 1, "allowedLicences": list(ALLOWED_LICENCES), "sounds": []}
    return json.loads(p.read_text(encoding="utf-8"))


def save_sources(doc: dict, sounds: Path = SOUNDS) -> None:
    doc["sounds"].sort(key=lambda e: e["path"])
    (sounds / SOURCES).write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def build_placeholders(sounds: Path = SOUNDS, date: str | None = None) -> list[str]:
    """(Re)generate the procedural placeholders and their SOURCES.json entries; other entries are kept as they are."""
    doc = load_sources(sounds)
    keep = [e for e in doc["sounds"] if e.get("source", {}).get("kind") != "procedural"]
    old = {e["path"]: e for e in doc["sounds"]}
    date = date or dt.date.today().isoformat()
    made = []
    for cue, count in PLACEHOLDERS.items():
        for v in range(count):
            rel = f"library/{cue}/proc_{cue}_v{v}.wav"
            x = synth.make(cue, v)
            wavio.write(sounds / rel, x, synth.RATE)
            sha = wavio.sha256(sounds / rel)
            prev = old.get(rel)
            keep.append({
                "path": rel, "sha256": sha, "cue": cue, "placeholder": True, "licence": "project-own",
                "source": {"kind": "procedural", "generator": "pipeline/audio/synth.py", "recipe": cue, "variant": v,
                           "seed": synth._seed("t195", cue, v)},
                "evidence": "generated by this repository's own code (T-195 procedural voice); no third-party material",
                "added": prev["added"] if prev and prev.get("sha256") == sha else date,
                "seconds": round(len(x) / synth.RATE, 3), "rate": synth.RATE, "channels": 1,
            })
            made.append(rel)
    doc["sounds"] = keep
    doc.setdefault("allowedLicences", list(ALLOWED_LICENCES))
    save_sources(doc, sounds)
    return made


def check(sounds: Path = SOUNDS) -> list[str]:
    """Problems with the library (empty = fine)."""
    doc = load_sources(sounds)
    problems = []
    listed = {}
    for e in doc["sounds"]:
        p = e.get("path", "")
        if p in listed:
            problems.append(f"{p}: listed twice")
        listed[p] = e
        f = sounds / p
        if not f.is_file():
            problems.append(f"{p}: listed but missing")
            continue
        if wavio.sha256(f) != e.get("sha256"):
            problems.append(f"{p}: sha256 does not match SOURCES.json")
        if e.get("licence") not in ALLOWED_LICENCES:
            problems.append(f"{p}: licence {e.get('licence')!r} not in {ALLOWED_LICENCES}")
        if not e.get("cue"):
            problems.append(f"{p}: no cue")
        elif not p.startswith(f"library/{e['cue']}/"):
            problems.append(f"{p}: not under library/{e['cue']}/")
        src = e.get("source", {})
        if src.get("kind") != "procedural":
            if not e.get("evidence"):
                problems.append(f"{p}: non-procedural sound without licence evidence")
            if not (src.get("url") or src.get("by")):
                problems.append(f"{p}: non-procedural sound without source.url or source.by")
            if e.get("licence") == "project-own" and not src.get("by"):
                problems.append(f"{p}: project-own needs source.by (who recorded it)")
        if "placeholder" not in e:
            problems.append(f"{p}: placeholder flag missing")
    for f in sorted((sounds / "library").rglob("*")):
        if f.is_file():
            rel = f.relative_to(sounds).as_posix()
            if rel not in listed:
                problems.append(f"{rel}: file without a SOURCES.json entry")
            if f.suffix.lower() != ".wav":
                problems.append(f"{rel}: only .wav files belong in the library")
    return problems


def candidates(cue: str, sounds: Path = SOUNDS) -> list[dict]:
    """Entries for `cue`, real ones first-and-only when any exist, sorted by path."""
    es = [e for e in load_sources(sounds)["sounds"] if e.get("cue") == cue]
    real = [e for e in es if not e.get("placeholder")]
    return sorted(real or es, key=lambda e: e["path"])


if __name__ == "__main__":
    import argparse
    import sys
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("command", choices=["build", "check"])
    a = ap.parse_args()
    if a.command == "build":
        print("\n".join(build_placeholders()))
    probs = check()
    print("\n".join(probs) or "library OK")
    sys.exit(1 if probs else 0)
